// invariants.test.mjs — CI checks for build-rule invariants I3, I4 and I7 (BUILD-RULES.md §4, lead call L1078).
// The scan is invariants-scan.mjs; its header says what each check flags and what it cannot see. A failure names the
// site: fix the code, or put the site on invariants-allowed.json with its own reason (`node
// orchestrate/test/invariants-scan.mjs` prints what the scan finds now, reasons kept, for that list).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { productionFiles, scanI3, scanI4, scanI7, textsIn, compare, keyI, keyI7, readList, GENERATED, BASELINE, LIST } from './invariants-scan.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
// The BASELINE entries each check may still have: the sites found on the day the checks started (L1078). Lower a cap
// when a baseline site is fixed; never raise one. A new site is listed with its own reason instead.
const BASELINE_CAP = Object.freeze({ I3: 0, I4: 0, I7: 100 });
const KEYS = { I3: keyI, I4: keyI, I7: keyI7 };
const SCANS = { I3: scanI3, I4: scanI4, I7: scanI7 };
const WHAT = {
  I3: 'a once-mark: a hold told once and never again while it lasts (I3: re-tell through stillWaiting)',
  I4: 'a stored time read outside pastTime (I4)',
  I7: 'a second copy of a definition or text (I7: one definition per concept)',
};

const list = readList(ROOT);
const files = productionFiles(ROOT);
const show = (e) => (e.kind ? `${e.kind} "${e.copy}" in ${e.files.join(', ')}` : `${e.file}: ${e.line}`);

test('the allowed list: three checks, and every entry has a reason', () => {
  assert.deepEqual(Object.keys(list).sort(), ['I3', 'I4', 'I7']);
  for (const [k, entries] of Object.entries(list)) {
    for (const e of entries) {
      assert.ok(typeof e.why === 'string' && e.why.trim() !== '' && !e.why.startsWith('NEW:'), `${LIST} ${k}: ${show(e)} has no reason`);
      if (k === 'I7') assert.ok(['definition', 'text'].includes(e.kind) && typeof e.copy === 'string' && Array.isArray(e.files) && e.files.length > 1, `${k}: ${JSON.stringify(e)}`);
      else assert.ok(typeof e.file === 'string' && typeof e.line === 'string', `${k}: ${JSON.stringify(e)}`);
    }
  }
});

for (const k of ['I3', 'I4', 'I7']) {
  test(`${k}: every site the scan finds is on the allowed list, and every listed site is still there`, () => {
    const { fresh, gone } = compare(SCANS[k](files), list[k], KEYS[k]);
    const lines = [
      ...fresh.map((e) => `  new, not on the list: ${show(e)}`),
      ...gone.map((e) => `  listed, no longer found (take it off ${LIST}): ${show(e)}`),
    ];
    assert.equal(lines.length, 0, `${k}, ${WHAT[k]}:\n${lines.join('\n')}\nFix the code, or list the site in ${LIST} with its own reason (node orchestrate/test/invariants-scan.mjs prints the scan).`);
  });

  test(`${k}: the baseline part of the list only shrinks (at most ${BASELINE_CAP[k]})`, () => {
    const n = list[k].filter((e) => e.why === BASELINE).length;
    assert.ok(n <= BASELINE_CAP[k], `${k} has ${n} entries marked "${BASELINE}", above its cap ${BASELINE_CAP[k]}: a new site needs its own reason`);
  });
}

test('I4: pastTime is the one listed home of the read, with its own reason', () => {
  const home = list.I4.filter((e) => e.file === 'shared/still-waiting.mjs');
  assert.equal(home.length, 1);
  assert.match(home[0].line, /Date\.parse\(value\)/);
  assert.notEqual(home[0].why, BASELINE);
});

test('the one skipped file is a generated bundle, and is the only one', () => {
  for (const rel of GENERATED) assert.match(readFileSync(join(ROOT, rel), 'utf8').split('\n')[0], /— GENERATED by build-checker\.mjs/);
  const skipped = new Set(GENERATED);
  assert.ok(files.every((f) => !skipped.has(f.rel)));
  assert.ok(files.length > 200, `only ${files.length} production files found`);
});

// ---- the scans themselves, on small sources ----
const one = (src, rel = 'a.mjs') => [{ rel, src }];

test('I3 control: a stored told flag set to true is flagged; a local variable, a string, a comment or a test of it is not', () => {
  const flagged = [
    "tellThen(alert, t, { fact: F, fields: { told: true }, kind: 'x' });",
    'tellThen(alert, t, { fields: { start_failed_told: true } });',
    'st.gave_up_told = true;',
    'st . alerted=true;',
    'doc = { warned: true, notified : true };',
  ];
  assert.deepEqual(flagged.map((s) => scanI3(one(s)).length), [1, 1, 1, 1, 2]);
  const quiet = [
    'let told = true;',
    'told = true;',
    "const s = 'told: true';",
    '// fields: { told: true }',
    'if (st.told === true) x();',
    'return { untold: true };',
    'const t = { told_at: iso(now), told: false };',
  ];
  for (const s of quiet) assert.deepEqual(scanI3(one(s)), [], s);
  assert.deepEqual(scanI3(one('a();\n  st.stop_told  =  true;\n')), [{ file: 'a.mjs', line: 'st.stop_told = true;' }]);
});

test('I4 control: Date.parse and new Date(x).getTime() are flagged; now(), a string, a comment or another parse are not', () => {
  const flagged = ['const t = Date.parse(doc.at);', 'Date . parse(x)', 'const t = new Date(doc.at).getTime();', 'new Date(s).valueOf()'];
  for (const s of flagged) assert.equal(scanI4(one(s)).length, 1, s);
  const quiet = ['const t = now().getTime();', 'new Date().getTime()', "'Date.parse(x)'", '// Date.parse(x)', 'pastTime(doc.at, now)', 'JSON.parse(x)', 'myDate.parse(x)'];
  for (const s of quiet) assert.deepEqual(scanI4(one(s)), [], s);
});

test('I7 control: the same constant or text in two files is flagged; one file, another value, a short text, import.meta are not', () => {
  const a = { rel: 'a.mjs', src: "export const LIMIT_MS = 5 * 60_000;\nconst HERE = dirname(fileURLToPath(import.meta.url));\nalert('the review threads could not be read today');\nconst W = 1;" };
  const b = { rel: 'b.mjs', src: "const LIMIT_MS = 5 *  60_000;\nconst HERE = dirname(fileURLToPath(import.meta.url));\nthrow new Error(`the review threads could not be read today`);\nconst W = 2;" };
  assert.deepEqual(scanI7([a, b]), [
    { kind: 'definition', copy: 'LIMIT_MS = 5 * 60_000', files: ['a.mjs', 'b.mjs'] },
    { kind: 'text', copy: 'the review threads could not be read today', files: ['a.mjs', 'b.mjs'] },
  ]);
  const twiceInOne = { rel: 'c.mjs', src: "say('the review threads could not be read today'); say('the review threads could not be read today');" };
  assert.deepEqual(scanI7([twiceInOne]), []);
  assert.deepEqual(scanI7([{ rel: 'd.mjs', src: "say('too short to count');" }, { rel: 'e.mjs', src: "say('too short to count');" }]), []);
  // A comment is not a text; a template is split at each ${ }.
  assert.deepEqual(scanI7([{ rel: 'f.mjs', src: '// the review threads could not be read today' }, b]).filter((x) => x.kind === 'text'), []);
  assert.deepEqual(textsIn('x(`the card ${id} is held: ${why}`)'), ['the card ', ' is held: ']);
});

test('compare: as multisets, so a second copy of a listed line is new', () => {
  const e = { file: 'a.mjs', line: 'Date.parse(x)' };
  assert.deepEqual(compare([e, e], [e], keyI), { fresh: [e], gone: [] });
  assert.deepEqual(compare([], [e], keyI), { fresh: [], gone: [e] });
});
