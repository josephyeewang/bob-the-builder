// workflow.mjs — writes the outside check's workflow file (R-0b-72; review-0b-7 M13, M14 and minors). The committed
// `.github/workflows/outside-check.yml` must equal `node workflow.mjs` output; a test checks that, so the YAML is never
// hand-edited and the rules below hold by construction.
//
//   - schedule trigger only (no workflow_dispatch, no push / pull_request / issues): a PR or an issue from another
//     account can start nothing.
//   - workflow default `permissions: {}`; three jobs, each with only what it needs:
//       check       holds the one read-only token secret, `permissions: {}`; it fetches this public repo at the run's commit with
//                   plain git (no third-party actions), then runs one step per (product slot, check), named
//                   "product N / <check>", each `if: ${{ !cancelled() }}` so one failure doesn't hide the others;
//       notify      no secrets, `issues: write` (this repo only): one updated issue per failing step;
//       keep-alive  `contents: write`: a commit when the repo has been quiet ~50 days, so GitHub doesn't switch the
//                   schedule off at 60 (unverified that a GITHUB_TOKEN commit counts: the day-61 re-check, README).
//   - no product data in any step: the product list comes from the PRODUCTS secret at run time and logs print only
//     the slot label and a reason code.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const CHECKS = Object.freeze(['heartbeat', 'audit-files', 'audit-run', 'deploys', 'permissions', 'robot-merges']);
export const SLOTS = 3;

export function workflowYaml({ slots = SLOTS, cron = '17 * * * *' } = {}) {
  const steps = [];
  for (let n = 1; n <= slots; n++) {
    for (const c of CHECKS) {
      steps.push(
        `      - name: product ${n} / ${c}`,
        `        if: \${{ !cancelled() }}`,
        `        run: node src/outside-check.mjs ${c} ${n}`,
      );
    }
  }
  return `# Generated by workflow.mjs. Do not edit by hand: change workflow.mjs and run \`node workflow.mjs\`.
name: outside-check
on:
  schedule:
    - cron: '${cron}'
permissions: {}
concurrency:
  group: outside-check
  cancel-in-progress: false
jobs:
  check:
    runs-on: ubuntu-latest
    timeout-minutes: 15
    permissions: {}
    outputs:
      ran: \${{ steps.collect.outputs.ran }}
      failed: \${{ steps.collect.outputs.failed }}
    env:
      PRODUCTS: \${{ secrets.PRODUCTS }}
      CHECK_TOKEN: \${{ secrets.CHECK_TOKEN }}
      RESULTS: results.txt
    steps:
      - name: get the check code
        run: git init -q src && git -C src fetch -q --depth 1 "https://github.com/$GITHUB_REPOSITORY" "$GITHUB_SHA" && git -C src checkout -q FETCH_HEAD
${steps.join('\n')}
      - name: collect
        id: collect
        if: \${{ always() }}
        run: node src/collect.mjs
  notify:
    needs: check
    if: \${{ always() && needs.check.outputs.ran != '' }}
    runs-on: ubuntu-latest
    timeout-minutes: 5
    permissions:
      issues: write
    env:
      GH_TOKEN: \${{ github.token }}
      RAN: \${{ needs.check.outputs.ran }}
      FAILED: \${{ needs.check.outputs.failed }}
    steps:
      - name: get the notify code
        run: git init -q src && git -C src fetch -q --depth 1 "https://github.com/$GITHUB_REPOSITORY" "$GITHUB_SHA" && git -C src checkout -q FETCH_HEAD
      - name: one issue per failing check
        run: node src/notify.mjs
  keep-alive:
    runs-on: ubuntu-latest
    timeout-minutes: 5
    permissions:
      contents: write
    env:
      GH_TOKEN: \${{ github.token }}
    steps:
      - name: get the keep-alive code
        run: git init -q src && git -C src fetch -q --depth 1 "https://github.com/$GITHUB_REPOSITORY" "$GITHUB_SHA" && git -C src checkout -q FETCH_HEAD
      - name: commit if quiet for 50 days
        run: node src/keep-alive.mjs
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('./.github/workflows/outside-check.yml', import.meta.url), workflowYaml());
}
