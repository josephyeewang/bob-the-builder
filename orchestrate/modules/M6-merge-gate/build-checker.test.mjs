// build-checker.test.mjs — the generated github-checker.mjs: rebuilt byte-identical, runs alone, fails loudly (R-0b-93).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';
import { tempDir } from '../../shared/test-tmp.mjs';
import { buildChecker, ZERO_COMMIT, OUTPUT_NAME } from './build-checker.mjs';
import { runChecker as runUnbundled } from './checker-entry.mjs';
import { plantedRepo } from './fixtures/checker-repo.mjs';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const ENTRY = join(HERE, 'checker-entry.mjs');
const COMMITTED = join(HERE, OUTPUT_NAME);

test('rebuilding with the zero commit gives the committed github-checker.mjs, byte for byte', () => {
  const built = buildChecker({ entry: ENTRY, sourceCommit: ZERO_COMMIT });
  assert.equal(built, readFileSync(COMMITTED, 'utf8'), 'github-checker.mjs is stale or hand-edited: run node build-checker.mjs <commit>');
  assert.match(built, /^\/\/ github-checker\.mjs — GENERATED by build-checker\.mjs from checker-entry\.mjs — do not edit\n\/\/ source commit: 0{40}\n/);
  assert.ok(buildChecker({ entry: ENTRY, sourceCommit: 'a'.repeat(40) }).includes(`// source commit: ${'a'.repeat(40)}\n`));
});

test('the bundle, copied alone into an empty folder, judges a planted repo the same as the unbundled checker', async () => {
  const dir = tempDir('m6-bundle-');
  const copy = join(dir, OUTPUT_NAME);
  copyFileSync(COMMITTED, copy);
  const b = await import(pathToFileURL(copy).href);
  assert.equal(typeof b.runChecker, 'function');
  assert.equal(typeof b.main, 'function');

  const p = plantedRepo();
  const docs = p.merge({ 'docs/research/a.md': 'two' });
  assert.deepEqual(await b.runChecker(p.args(docs.m)), { ok: true, flags: [], judged: true });
  assert.deepEqual(await b.runChecker(p.args(docs.m)), await runUnbundled(p.args(docs.m)));

  const q = plantedRepo();
  const hand = q.merge({ 'docs/research/a.md': 'two' }, { marked: false });
  const r = await b.runChecker(q.args(hand.m));
  assert.equal(r.ok, false);
  assert.ok(r.flags.some((f) => /no robot mark/.test(f)) && r.flags.some((f) => /no pull request/.test(f)), r.flags.join('|'));
  assert.deepEqual(r, await runUnbundled(q.args(hand.m)));

  // A policy.yaml change goes through classify ↔ policy (the import cycle) and must still need the owner.
  const s = plantedRepo();
  const rules = s.merge({ 'orchestrate/policy.yaml': 'version: 1\n' });
  const rb = await b.runChecker(s.args(rules.m));
  assert.equal(rb.ok, false);
  assert.deepEqual(rb, await runUnbundled(s.args(rules.m)));
});

test('run directly, the bundle runs main like checker-entry does', () => {
  const dir = tempDir('m6-bundle-cli-');
  const copy = join(dir, OUTPUT_NAME);
  copyFileSync(COMMITTED, copy);
  const pass = join(dir, 'pass.json');
  writeFileSync(pass, JSON.stringify({ ok: true, flags: [] }));
  const flagged = join(dir, 'flagged.json');
  writeFileSync(flagged, JSON.stringify({ ok: false, flags: ['x'] }));
  const run = (file) => spawnSync(process.execPath, [copy, 'verdict', file], { cwd: dir, encoding: 'utf8' });
  const a = run(pass);
  assert.equal(a.status, 0, a.stderr);
  assert.match(a.stdout, /checker: passed/);
  assert.equal(run(flagged).status, 1);
});

test('a bad source commit throws', () => {
  for (const c of [undefined, '', 'abc', 'A'.repeat(40), `${ZERO_COMMIT}0`, 'g'.repeat(40)]) {
    assert.throws(() => buildChecker({ entry: ENTRY, sourceCommit: c }), /40-hex/);
  }
});

test('an import or export form the builder does not understand throws, naming the module', () => {
  const cases = {
    'dynamic import': ["export async function f() { return import('./b.mjs'); }\n", /a\.mjs: dynamic import/],
    'default export': ['export default function f() {}\n', /a\.mjs: default export/],
    'export *': ["export * from './b.mjs';\n", /a\.mjs: export \*/],
    'JSON import with attributes': ["import data from './d.json' with { type: 'json' };\nexport const x = data;\n", /a\.mjs: (import form not understood|unfinished import)/],
    'JSON import': ["import { d } from './d.json';\nexport const x = d;\n", /a\.mjs: only \.mjs\/\.js/],
    'bare package': ["import { x } from 'some-package';\nexport const y = x;\n", /a\.mjs: not a relative or node: import/],
    'bare built-in name': ["import { readFileSync } from 'fs';\nexport const y = readFileSync;\n", /a\.mjs: not a relative or node: import/],
    'default import of a module': ["import b from './b.mjs';\nexport const y = b;\n", /a\.mjs: default import of/],
    'import.meta outside the entry': ["import { y } from './c.mjs';\nexport const z = y;\n", /c\.mjs: import\.meta outside the entry/],
    'an imported name not exported': ["import { nope } from './b.mjs';\nexport const z = nope;\n", /a\.mjs: imports nope, which b\.mjs does not export/],
    'destructured export': ['export const { a } = { a: 1 };\n', /a\.mjs: export form not understood/],
  };
  for (const [name, [src, why]] of Object.entries(cases)) {
    const dir = tempDir('m6-bad-');
    writeFileSync(join(dir, 'b.mjs'), 'export const b = 1;\n');
    writeFileSync(join(dir, 'c.mjs'), 'export const y = import.meta.url;\n');
    writeFileSync(join(dir, 'a.mjs'), src);
    assert.throws(() => buildChecker({ entry: join(dir, 'a.mjs'), sourceCommit: ZERO_COMMIT, root: dir }),
      (e) => /^build-checker: [a-z]\.mjs: /.test(e.message) && why.test(e.message), name);
  }
});

test('the bundle names no relative import and no absolute path', () => {
  const text = readFileSync(COMMITTED, 'utf8');
  assert.ok(!text.includes("from './") && !text.includes("from '../") && !text.includes('from "./') && !text.includes('from "../'));
  const root = fileURLToPath(new URL('../../../', import.meta.url));
  assert.ok(!text.includes(root.replace(/\/$/, '')), 'contains this machine\'s repo path');
  assert.doesNotMatch(text, /\/(Users|home|private|tmp|var\/folders)\/|[A-Z]:\\\\/);
  for (const line of text.split('\n').filter((l) => /^import /.test(l))) assert.match(line, /^import \* as __bob_node_\w+ from 'node:[a-z/_]+';$/);
});
